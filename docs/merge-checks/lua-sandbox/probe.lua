-- what a level script can reach in a plain luaL_openlibs() state (the fork today)
local function try(name, f) local ok, r = pcall(f); print(string.format("%-34s %s", name, ok and ("YES "..tostring(r)) or ("no  "..tostring(r):sub(1,50)))) end
try("ffi library loaded",            function() return type(ffi) end)
try("require('ffi')",                function() return type(require('ffi')) end)
try("ffi: call libc system()",       function() local ffi=require('ffi'); ffi.cdef"int system(const char*);"; return ffi.C.system("echo   [escaped via ffi]") end)
try("ffi: read arbitrary memory",    function() local ffi=require('ffi'); return type(ffi.cast("char*", 0)) end)
try("jit library",                   function() return type(jit) end)
try("io.open write a file",          function() local f=assert(io.open("probe_written.txt","w")); f:write("x"); f:close(); return "wrote" end)
try("io.open read /etc/hostname",    function() local f=assert(io.open("/etc/hostname","r")); local s=f:read("*l"); f:close(); return "read "..#s.." bytes" end)
try("os.remove",                     function() return tostring(os.remove("probe_written.txt")) end)
try("os.execute",                    function() return tostring(os.execute("echo   [escaped via os.execute]")) end)
try("io.popen",                      function() local p=io.popen("echo   [escaped via popen]"); local s=p:read("*l"); p:close(); return s end)
try("os.getenv('HOME')",             function() return tostring(os.getenv("HOME")) end)
try("os.rename",                     function() return type(os.rename) end)
try("os.tmpname",                    function() return type(os.tmpname) end)
try("os.exit",                       function() return type(os.exit) end)
try("package.loadlib",               function() return type(package.loadlib) end)
try("require C module via cpath",    function() return package.cpath end)
try("dofile / loadfile",             function() return type(dofile)..","..type(loadfile) end)
try("load bytecode (string.dump)",   function() local f=load(string.dump(function() return 42 end), nil, "b"); return f() end)
try("debug library",                 function() return type(debug.getregistry()) end)
try("debug.setmetatable on numbers", function() debug.setmetatable(0, {__index=math}); return "ok" end)
try("setfenv / getfenv",             function() return type(setfenv) end)
try("collectgarbage('count')",       function() return type(collectgarbage("count")) end)
try("infinite loop guard",           function() return "none (no instruction/time limit)" end)
